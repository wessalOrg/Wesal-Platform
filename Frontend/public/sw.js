/**
 * Wesal Service Worker — production-safe, installability-focused.
 *
 * Goals:
 * - Make the site installable (fetch handler + precached offline fallback).
 * - NEVER cache auth/API/private data (login, JWT, bookings, messages,
 *   uploads, payments, notifications, SignalR).
 * - NEVER serve a stale app shell: navigations are network-first and are
 *   never written to cache; only versioned static assets use
 *   stale-while-revalidate.
 * - New deployments activate fast (skipWaiting on demand) without trapping
 *   users on an old bundle.
 */

const SW_VERSION = "wesal-v1";
const STATIC_CACHE = `wesal-static-${SW_VERSION}`;
const OFFLINE_URL = "/offline.html";

// Best-effort precache: offline fallback + installability icons.
// The manifest itself is generated by Next.js at /manifest.webmanifest.
const PRECACHE_URLS = [
  OFFLINE_URL,
  "/icons/icon-192.png",
  "/icons/icon-512.png",
  "/icons/maskable-192.png",
  "/icons/maskable-512.png",
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      try {
        const cache = await caches.open(STATIC_CACHE);
        await cache.addAll(PRECACHE_URLS);
      } catch {
        // Offline at first install or a single asset failed — stay installable anyway.
      }
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter((key) => key.startsWith("wesal-static-") && key !== STATIC_CACHE)
          .map((key) => caches.delete(key)),
      );
      await self.clients.claim();
    })(),
  );
});

// Allow the page to trigger immediate activation for a waiting update.
self.addEventListener("message", (event) => {
  if (event.data === "WESAL_SKIP_WAITING") {
    self.skipWaiting();
  }
});

/** Requests that must always go straight to the network, never cached. */
function isBypassed(url, request) {
  // API / realtime / uploads — same-origin Next API routes AND any path that
  // looks like backend traffic. Cross-origin (Render API, Unsplash, fonts…)
  // is handled separately below, but double-guard API-looking paths anyway.
  if (url.pathname.startsWith("/api/")) return true;
  if (url.pathname.includes("/uploads")) return true;
  if (url.pathname.includes("signalr") || url.pathname.includes("hub")) return true;
  // Note: /login, /register, /forgot-password, /reset-password and every
  // other navigation is network-first and never written to cache (see the
  // navigate branch below), so auth pages always load fresh from the server.
  // Authenticated XHR/fetch carries a Bearer token — never cache it.
  try {
    if (request.headers.get("authorization")) return true;
  } catch {
    /* ignore */
  }
  return false;
}

/** Public, versioned static assets safe for stale-while-revalidate. */
function isStaticAsset(url, request) {
  if (request.destination === "style") return true;
  if (request.destination === "script") return true;
  if (request.destination === "font") return true;
  if (request.destination === "image") return true;
  if (url.pathname.startsWith("/_next/static/")) return true;
  if (url.pathname.startsWith("/icons/")) return true;
  if (url.pathname.startsWith("/hero/")) return true;
  if (url.pathname.startsWith("/halls/")) return true;
  if (url.pathname.startsWith("/footer/")) return true;
  if (url.pathname.startsWith("/how/")) return true;
  if (url.pathname.startsWith("/assistant/")) return true;
  if (url.pathname.startsWith("/auth/")) return true;
  return /\.(?:png|jpe?g|webp|avif|gif|svg|ico|css|js|woff2?)$/i.test(url.pathname);
}

async function staleWhileRevalidate(request) {
  const cache = await caches.open(STATIC_CACHE);
  const cached = await cache.match(request, { ignoreSearch: false });
  const networkPromise = fetch(request)
    .then((response) => {
      // Cache only clean, public, successful responses.
      const contentType = response.headers.get("content-type") || "";
      const isCacheableType =
        contentType.includes("image/") ||
        contentType.includes("text/css") ||
        contentType.includes("javascript") ||
        contentType.includes("font") ||
        contentType === "";
      if (
        response.ok &&
        isCacheableType &&
        !contentType.includes("application/json")
      ) {
        cache.put(request, response.clone()).catch(() => {});
      }
      return response;
    })
    .catch(() => cached);
  return cached || networkPromise;
}

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return; // POST/PUT/DELETE/uploads/payments untouched.

  let url;
  try {
    url = new URL(request.url);
  } catch {
    return;
  }

  // Cross-origin (backend API on Render, Unsplash, Google Fonts…): passthrough.
  if (url.origin !== self.location.origin) return;

  if (isBypassed(url, request)) return; // network-only.

  // App navigations (incl. opening the installed app on any route):
  // network-first, never cached, offline fallback only when fully offline.
  if (request.mode === "navigate") {
    event.respondWith(
      (async () => {
        try {
          return await fetch(request);
        } catch {
          const cache = await caches.open(STATIC_CACHE);
          const offline = await cache.match(OFFLINE_URL);
          if (offline) return offline;
          throw new Error("offline");
        }
      })(),
    );
    return;
  }

  if (isStaticAsset(url, request)) {
    event.respondWith(staleWhileRevalidate(request));
  }
  // Anything else same-origin GET (RSC payloads, dynamic JSON…): network-only.
});
